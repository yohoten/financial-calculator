def case2() -> dict:
    section("用例 2 | 教育金定投 —— 每年存 2 万，10 年后能攒多少？")
    print("场景设定：李先生为子女准备留学教育金，每年末存入 20,000 元，年化收益 5%，连续 10 年。")
    print("对照方案：若改为每年初存入（预付年金），终值有何差异？\n")

    pmt, r, n = 20_000, 0.05, 10
    fva_o = core.fva_ordinary(pmt, r, n)
    fva_d = core.fva_due(pmt, r, n)
    pva_o = core.pva_ordinary(pmt, r, n)
    pva_d = core.pva_due(pmt, r, n)
    total = pmt * n

    print("【计算过程】")
    print(f"  1) 普通年金终值 FVA = {pmt:,.0f} × [((1+{r:.0%})^{n} - 1) / {r:.0%}] = {fva_o:,.2f} 元")
    print(f"  2) 预付年金终值 = FVA × (1 + r) = {fva_d:,.2f} 元")
    print(f"  3) 普通年金现值 PVA = {pva_o:,.2f} 元")
    print(f"  4) 年金现值系数 (P/A, 5%, 10) = {pva_o / pmt:.6f}")
    print(f"  5) 年金终值系数 (F/A, 5%, 10) = {fva_o / pmt:.6f}（教材附表可查，应与本结果一致）\n")

    check("普通年金终值系数 (F/A,5%,10)", fva_o / pmt, 12.577892, 1e-5)
    check("普通年金终值 FVA", fva_o, 251_557.8507, 0.01)
    check("预付年金终值", fva_d, 264_135.7432, 0.01)
    check("年金现值系数 (P/A,5%,10)", pva_o / pmt, 7.721734, 1e-5)
    check("普通年金现值 PVA", pva_o, 154_434.6986, 0.01)
    check("预付年金现值", pva_d, 162_156.4335, 0.01)

    print("\n【业务解读】")
    print(f"· 累计投入本金 {total:,.0f} 元，10 年后可得 {fva_o:,.2f} 元，投资收益 "
          f"{fva_o - total:,.2f} 元，占总资产的 {(fva_o - total)/fva_o:.1%}，复利贡献显著。")
    print(f"· 改为每年初存入，终值提升 {fva_d - fva_o:,.2f} 元（+{(fva_d/fva_o-1):.2%}），"
          f"原因是每笔款项都多计息一期。这解释了保险、教育金产品为什么强调“尽早缴费”。")
    print(f"· 反过来看：若一次性拿出 {pva_o:,.2f} 元作为本金，也能实现每年取 2 万、连续 10 年的目标，"
          f"这为“整存零取”式的养老规划提供了计算依据。")
    return {"名称": "用例2 教育金定投年金", "参数": {"每期PMT": pmt, "年利率": r, "期数": n},
            "过程": [("普通年金终值", f"{fva_o:,.2f}"), ("预付年金终值", f"{fva_d:,.2f}"),
                     ("普通年金现值", f"{pva_o:,.2f}"), ("预付年金现值", f"{pva_d:,.2f}"),
                     ("(F/A,5%,10)", f"{fva_o/pmt:.6f}"), ("(P/A,5%,10)", f"{pva_o/pmt:.6f}")],
            "结论": f"10 年后可积累 {fva_o:,.2f} 元；改为期初存入可多得 {fva_d-fva_o:,.2f} 元。"}


