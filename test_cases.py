def case6() -> dict:
    section("用例 6 | 房贷还款计划 —— 等额本息下的利息构成（年金公式逆向应用）")
    print("场景设定：小王贷款 100 万元购房，年利率 4.2%（月利率 0.35%），期限 20 年，")
    print("          采用等额本息还款，每月还款一次。\n")

    P, rate, years, freq = 1_000_000, 0.042, 20, 12
    s = core.amortization_schedule(P, rate, years, freq)
    r_m = rate / freq
    n = years * freq
    verify = core.pva_ordinary(s["每期还款额"], r_m, n)

    print("【计算过程】")
    print(f"  1) 期利率 r = {rate:.2%} / 12 = {r_m:.4%}，总期数 n = {years} × 12 = {n}")
    print(f"  2) 月供 PMT = P × r / [1 - (1+r)^(-n)] = {s['每期还款额']:,.2f} 元")
    print(f"  3) 总还款额 = {s['每期还款额']:,.2f} × {n} = {s['总还款额']:,.2f} 元")
    print(f"  4) 总利息 = {s['总还款额']:,.2f} - {P:,.0f} = {s['总利息']:,.2f} 元")
    print(f"  5) 逆向校验：把月供按 {r_m:.4%} 折现 {n} 期 = {verify:,.6f} 元 ≈ 贷款本金 ✔\n")

    check("月供 PMT", s["每期还款额"], 6165.7074, 0.01)
    check("总利息", s["总利息"], 479_769.77, 0.5)
    check("月供的年金现值（应等于本金）", verify, 1_000_000.0, 1e-4)
    check("首期利息", s["计划表"][0]["利息"], 3500.0, 1e-6)

    print("\n【业务解读】")
    print(f"· 每月还款 {s['每期还款额']:,.2f} 元，20 年累计支付利息 {s['总利息']:,.2f} 元，"
          f"相当于本金的 {s['总利息']/P:.1%}——这就是长期贷款的真实资金成本。")
    print(f"· 首期月供中利息占 {s['计划表'][0]['利息']/s['每期还款额']:.1%}，本金仅占 "
          f"{s['计划表'][0]['本金']/s['每期还款额']:.1%}；而最后一期利息几乎为零。"
          f"前期还款主要在“还利息”，这是等额本息最容易被忽视的特征。")
    print(f"· 校验意义：月供的年金现值精确等于本金（{verify:,.2f} 元），"
          f"说明贷款定价与年金现值模型完全一致——房贷的本质就是“本金 = 各期还款的年金现值”。")
    print(f"· 决策提示：提前还款越早，节省利息越多。若在第 5 年末一次性还清，"
          f"可节省后续利息约 {s['总利息'] - sum(row['利息'] for row in s['计划表'][:60]):,.0f} 元"
          f"（估算口径：前 5 年已付利息之外的剩余利息）。")
    return {"名称": "用例6 房贷还款计划", "参数": {"贷款本金": P, "年利率": rate, "年限": years, "每年还款次数": freq},
            "过程": [("月供PMT", f"{s['每期还款额']:,.2f}"), ("总还款额", f"{s['总还款额']:,.2f}"),
                     ("总利息", f"{s['总利息']:,.2f}"), ("月供年金现值校验", f"{verify:,.6f}")],
            "结论": f"月供 {s['每期还款额']:,.2f} 元，总利息 {s['总利息']:,.2f} 元，"
                    f"年金现值逆向校验通过。"}


