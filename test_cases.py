# 用例 4：股权资本成本 CAPM
# =============================================================================
def case4() -> dict:
    section("用例 4 | 上市公司股权资本成本 —— CAPM 与 DDM 双重验证")
    print("场景设定：某 A 股上市公司 β = 1.20，10 年期国债收益率 2.5%，")
    print("          市场组合期望收益率 9.5%；公司预计下年每股股利 0.50 元，")
    print("          当前股价 12 元，股利年增长率 4%。\n")

    rf, beta, rm, d1, p0, g = 0.025, 1.20, 0.095, 0.50, 12.0, 0.04
    e = core.capm_required_return(rf, beta, rm)
    ks_ddm = core.cost_of_equity_ddm(d1, p0, g)

    print("【计算过程】")
    print(f"  1) 市场风险溢价 MRP = Rm - Rf = {rm:.2%} - {rf:.2%} = {e['市场风险溢价']:.2%}")
    print(f"  2) CAPM：Ks = {rf:.2%} + {beta} × {e['市场风险溢价']:.2%} = {e['股权资本成本']:.4%}")
    print(f"  3) 风险补偿占比 = {e['风险补偿部分']:.2%} / {e['股权资本成本']:.2%} = {e['风险补偿部分']/e['股权资本成本']:.1%}")
    print(f"  4) DDM：Ks = D1/P0 + g = {d1}/{p0} + {g:.2%} = {ks_ddm:.4%}")
    print(f"  5) 两模型差异 = {ks_ddm - e['股权资本成本']:+.4%}\n")

    check("市场风险溢价 MRP", e["市场风险溢价"], 0.07, 1e-9)
    check("CAPM 股权资本成本", e["股权资本成本"], 0.109, 1e-9)
    check("DDM 股权资本成本", ks_ddm, 0.081667, 1e-5)

    print("\n【业务解读】")
    print(f"· CAPM 给出 {e['股权资本成本']:.2%}，DDM 给出 {ks_ddm:.2%}，"
          f"差异 {(ks_ddm-e['股权资本成本'])*100:.2f} 个百分点。")
    print(f"· 差异主要源于假设口径不同：CAPM 基于市场风险定价（β 由历史股价回归得出），"
          f"DDM 基于分红能力定价（依赖增长率假设）。二者都合理，实务中常取 CAPM 为主、DDM 校验。")
    print(f"· β = {beta} > 1 表明该公司波动高于市场，投资者要求 {e['风险补偿部分']:.2%} 的风险补偿，"
          f"占股权成本的 {e['风险补偿部分']/e['股权资本成本']:.0%}，这部分正是“股权融资贵”的根源。")
    print(f"· 若市场风险溢价假设从 7% 降至 5%（如牛市预期降温），Ks 将降至 "
          f"{rf + beta*0.05:.2%}，下降 {(e['股权资本成本']-(rf+beta*0.05))*100:.2f} 个百分点，"
          f"说明 CAPM 结果对 MRP 假设高度敏感，测算时须审慎取值。")
    return {"名称": "用例4 股权资本成本CAPM", "参数": {"Rf": rf, "β": beta, "Rm": rm, "D1": d1, "P0": p0, "g": g},
            "过程": [("MRP", f"{e['市场风险溢价']:.4%}"), ("CAPM Ks", f"{e['股权资本成本']:.6%}"),
                     ("DDM Ks", f"{ks_ddm:.6%}"), ("两法差异", f"{ks_ddm-e['股权资本成本']:+.6%}")],
            "结论": f"CAPM 股权成本 {e['股权资本成本']:.4%}，DDM 交叉验证 {ks_ddm:.4%}，"
                    f"差异 {abs(ks_ddm-e['股权资本成本'])*100:.2f} 个百分点。"}


