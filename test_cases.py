def case3() -> dict:
    section("用例 3 | 企业债券发行资本成本 —— 折价发行的真实融资成本与税盾效应")
    print("场景设定：某制造企业发行面值 1,000 元、票面利率 6%、期限 5 年的公司债，")
    print("          由于市场利率上升，实际发行价为 950 元（折价发行），企业所得税率 25%。")
    print("问题：企业的税前、税后债务资本成本各是多少？\n")

    fv_, cpn, yrs, price, tax = 1000, 0.06, 5, 950, 0.25
    d = core.cost_of_debt(fv_, cpn, yrs, price, tax)
    dap = core.cost_of_debt_approx(fv_, cpn, yrs, price, tax)
    bp = core.bond_price(fv_, cpn, yrs, cpn)

    print("【计算过程】")
    print(f"  1) 年利息 C = 1000 × 6% = {fv_*cpn:,.2f} 元/年，5 年共 {fv_*cpn*yrs:,.2f} 元")
    print(f"  2) 建立方程：950 = Σ [60 / (1+k)^t] + 1000 / (1+k)^5 ，用牛顿迭代求 k")
    print(f"  3) 解得税前债务资本成本 Kd(税前) = {d['税前年化资本成本']:.4%}")
    print(f"  4) 税后成本 Kd(税后) = {d['税前年化资本成本']:.4%} × (1 - 25%) = {d['税后年化资本成本']:.4%}")
    print(f"  5) 近似公式校验：Kd ≈ [1000×6% + (1000-950)/5] / [(1000+950)/2] = "
          f"{dap['税前年化资本成本(近似)']:.4%}")
    print(f"  6) 两法差异 = {abs(d['税前年化资本成本'] - dap['税前年化资本成本(近似)']):.5%}（互为验证）\n")

    check("税前债务资本成本（YTM/IRR 法）", d["税前年化资本成本"], 0.072269, 1e-5)
    check("税后债务资本成本", d["税后年化资本成本"], 0.054202, 1e-5)
    check("近似公式法税前成本", dap["税前年化资本成本(近似)"], 0.071795, 1e-5)
    check("平价发行时的理论价格", bp["理论价格"], 1000.0, 0.01)

    print("\n【业务解读】")
    print(f"· 虽然票面利率只有 6%，但因折价发行，企业真实的税前债务成本达 {d['税前年化资本成本']:.3%}，"
          f"高出票面利率 {(d['税前年化资本成本']-cpn)*100:.3f} 个百分点——价格折让正是对投资者的额外补偿。")
    print(f"· 税盾效应使实际成本降至 {d['税后年化资本成本']:.3%}，每 100 元债务每年节省利息税负 "
          f"{d['税盾节省(百分点)']:.3f} 元。若企业不盈利、无法使用税盾，则应按税前成本计量。")
    print(f"· 与股权成本相比，债务成本明显更低（本例税后 {d['税后年化资本成本']:.3%}），"
          f"这是企业青睐债务融资的核心原因，也是 WACC 随适度负债而下降的机理。")
    print(f"· 债券定价校验：以票面利率 {cpn:.1%} 折现时理论价格恰为面值 1,000 元，"
          f"说明“票面利率=市场利率时债券平价发行”这一结论成立，模型自洽。")
    return {"名称": "用例3 企业债券资本成本", "参数": {"面值": fv_, "票面利率": cpn, "期限": yrs, "发行价": price, "税率": tax},
            "过程": [("税前债务成本(YTM)", f"{d['税前年化资本成本']:.6%}"),
                     ("税后债务成本", f"{d['税后年化资本成本']:.6%}"),
                     ("近似公式法", f"{dap['税前年化资本成本(近似)']:.6%}"),
                     ("税盾节省(百分点)", f"{d['税盾节省(百分点)']:.4f}")],
            "结论": f"税前债务成本 {d['税前年化资本成本']:.4%}，税后 {d['税后年化资本成本']:.4%}，"
                    f"税盾每年节省 {d['税盾节省(百分点)']:.3f} 个百分点。"}


