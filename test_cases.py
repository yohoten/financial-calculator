def case1() -> dict:
    section("用例 1 | 个人储蓄复利增值 —— 小张的 10 万元五年后值多少")
    print("场景设定：小张将 100,000 元存入 5 年期理财，年化利率 6%，按年复利计息。")
    print("问题：5 年后本息合计多少？若改为按月复利，又能多拿多少？\n")

    pv, r, n = 100_000, 0.06, 5
    fv_year = core.fv_compound(pv, r, n, 1)
    fv_month = core.fv_compound(pv, r, n, 12)
    fv_quarter = core.fv_compound(pv, r, n, 4)
    ear_year = core.effective_annual_rate(r, 1)
    ear_month = core.effective_annual_rate(r, 12)
    pv_back = core.pv_compound(200_000, r, n, 1)

    print("【计算过程】")
    print(f"  1) 年复利终值 FV = {pv:,.0f} × (1 + {r:.2%})^5 = {fv_year:,.2f} 元")
    print(f"  2) 按季复利 FV = {pv:,.0f} × (1 + {r/4:.4%})^20 = {fv_quarter:,.2f} 元")
    print(f"  3) 按月复利 FV = {pv:,.0f} × (1 + {r/12:.6%})^60 = {fv_month:,.2f} 元")
    print(f"  4) 实际年利率 EAR(月复利) = (1 + {r/12:.6%})^12 - 1 = {ear_month:.4%}")
    print(f"  5) 已知 5 年后要拿到 20 万，问现在需存多少：PV = {pv_back:,.2f} 元\n")

    check("年复利终值（10万，6%，5年）", fv_year, 133_822.5578, 0.01)
    check("季复利终值", fv_quarter, 134_685.5007, 0.01)
    check("月复利终值", fv_month, 134_885.0153, 0.01)
    check("实际年利率 EAR（月复利）", ear_month, 0.061678, 1e-5)
    check("20万的复利现值（5年，6%）", pv_back, 149_451.6346, 0.01)
    print("\n【业务解读】")
    for line in [
        f"· 年复利下资金 5 年增长 {fv_year / pv - 1:.2%}，10 万变 {fv_year:,.0f} 元。",
        f"· 计息频率效应明显：月复利比年复利多收益 {fv_month - fv_year:,.2f} 元，"
        f"相当于实际年利率从 {ear_year:.2%} 提升到 {ear_month:.2%}（+{(ear_month-ear_year)*100:.3f} 个百分点）。",
        f"· “72 法则”估算翻倍时间：72 / 6 = 12 年，与精确计算 {(np.log(2)/np.log(1.06)):.1f} 年基本吻合，"
        f"该法则可作快速心算工具。",
        "· 复利现值的意义：若目标是 5 年后积累 20 万元，今天只需存入 14.95 万元，"
        "这就是“货币时间价值”在个人理财规划中最直接的应用。",
    ]:
        print(line)
    return {"名称": "用例1 个人储蓄复利增值", "参数": {"现值PV": pv, "年利率": r, "年数": n, "计息方式": "年/季/月"},
            "过程": [("年复利终值", f"{fv_year:,.2f}"), ("季复利终值", f"{fv_quarter:,.2f}"),
                     ("月复利终值", f"{fv_month:,.2f}"), ("EAR(月复利)", f"{ear_month:.4%}"),
                     ("20万复利现值", f"{pv_back:,.2f}")],
            "结论": f"年复利终值 {fv_year:,.2f} 元；月复利终值 {fv_month:,.2f} 元，计息频率提升可额外增厚收益 {fv_month-fv_year:,.2f} 元。"}


